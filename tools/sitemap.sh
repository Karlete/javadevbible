#!/usr/bin/env bash
#
# sitemap.sh — regenerate javabible/sitemap.xml from the pages on disk.
#
# <lastmod> is the date of the last commit that touched each page, so search
# engines can tell which pages changed. Run it AFTER committing page edits
# (uncommitted changes have no commit date yet), then commit the sitemap:
#
#   bash tools/sitemap.sh && git add javabible/sitemap.xml
#
# verify.sh check 13 fails if the sitemap's URL list drifts from disk. It does
# not compare dates: CI checks out a shallow clone, where every file appears
# to have been last changed by the newest commit.
#
# Dependencies: bash, git, find, sort. Nothing else — same rule as verify.sh.

set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
SITE_ROOT="$REPO_ROOT/javabible"
BASE='https://karlete.github.io/javadevbible/javabible/'
OUT="$SITE_ROOT/sitemap.xml"

lastmod() {
  # %cs = committer date, YYYY-MM-DD. Empty for a file never committed.
  git -C "$REPO_ROOT" log -1 --format=%cs -- "javabible/$1" 2>/dev/null || true
}

{
  printf '<?xml version="1.0" encoding="UTF-8"?>\n'
  printf '<!-- Generated by tools/sitemap.sh. Do not edit by hand. -->\n'
  printf '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n'
  while IFS= read -r rel; do
    date="$(lastmod "$rel")"
    if [[ -n "$date" ]]; then
      printf '  <url><loc>%s%s</loc><lastmod>%s</lastmod></url>\n' "$BASE" "$rel" "$date"
    else
      printf '  <url><loc>%s%s</loc></url>\n' "$BASE" "$rel"
    fi
  done < <({ printf 'index.html\n'; find "$SITE_ROOT/topics" -name '*.html' | sed "s|^$SITE_ROOT/||" | sort; })
  printf '</urlset>\n'
} > "$OUT"

printf 'wrote %s (%s URLs)\n' "${OUT#"$REPO_ROOT/"}" "$(grep -c '<loc>' "$OUT")"
